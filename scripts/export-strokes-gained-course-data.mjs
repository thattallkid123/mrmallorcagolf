import fs from 'fs/promises'
import path from 'path'
import { fileURLToPath, pathToFileURL } from 'url'

const __filename = fileURLToPath(import.meta.url)
const __dirname = path.dirname(__filename)
const repoRoot = path.join(__dirname, '..')
const mmgToolsRoot = path.join(repoRoot, '..', 'mmg-tools')
const outputPath = path.join(mmgToolsRoot, 'strokes-gained', 'course-data.js')

const { MALLORCA_TRACKER_COURSES } = await import(
  pathToFileURL(path.join(repoRoot, 'src', 'lib', 'mallorca-tracker-courses.js')).href
)

const generatedAt = new Date().toISOString()
const payload = JSON.stringify(MALLORCA_TRACKER_COURSES, null, 2)
const content = `// Generated by mrmallorcagolf-real/scripts/export-strokes-gained-course-data.mjs
// Do not edit manually inside mmg-tools/strokes-gained/course-data.js.
// Source of truth: src/lib/scorecard-data.js + src/lib/course-access-data.js + src/lib/mallorca-tracker-courses.js
window.MMG_STROKES_GAINED_COURSES = ${payload};
window.MMG_STROKES_GAINED_COURSES_GENERATED_AT = ${JSON.stringify(generatedAt)};
`

await fs.writeFile(outputPath, content, 'utf8')
console.log(`Exported ${MALLORCA_TRACKER_COURSES.length} strokes-gained courses to ${outputPath}`)
