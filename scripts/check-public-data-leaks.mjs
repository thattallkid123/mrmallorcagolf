#!/usr/bin/env node
// Fails when business-private wording sits in a data file that ships to every visitor.
//
// Why: src/lib/course-pricing-data.js is imported by client components, so the whole object (every field, whether or
// not a page shows it) is served in the public JavaScript. On 2026-10-19 the live bundle was found carrying Andy's
// research notes ("Signed 2026 TO contract. 2027 contract is 55/74 - recheck"). Nothing was displayed, but anyone could
// read it. Net rates, TO discounts, minimum markups and contract terms live in mmg-tools and the Sheet, never here.
//
// This file is generated by mmg-tools/scripts/sync-pricing.js (publicJuniorPricing strips the notes). The check is the
// guard against a new field, or a hand edit, putting such wording back.

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..')
const files = ['src/lib/course-pricing-data.js']

const FORBIDDEN = [
  [/\bTO contract/i, 'mentions a TO contract'],
  [/signed (2026|2027)? ?contract/i, 'mentions a signed contract'],
  [/toDiscount|minimumMarkup|min(imum)? ?mark-?up/i, 'carries a TO discount or markup field'],
  [/net rate|net rates|commissionable/i, 'carries net-rate wording'],
  [/courtesy/i, 'mentions courtesy terms'],
  [/recheck|re-check|\bAndy\b/i, 'carries an internal working note'],
]

const problems = []
for (const rel of files) {
  const full = path.join(root, rel)
  if (!fs.existsSync(full)) continue
  const text = fs.readFileSync(full, 'utf8')
  for (const [pattern, why] of FORBIDDEN) {
    const m = text.match(pattern)
    if (m) {
      const at = text.indexOf(m[0])
      const line = text.slice(0, at).split('\n').length
      problems.push(`${rel}:${line} ${why}: "${text.slice(Math.max(0, at - 30), at + 60).replace(/\s+/g, ' ')}"`)
    }
  }
}

if (problems.length) {
  console.error('Public data leak check FAILED. Private business wording would ship in the public JavaScript:')
  problems.forEach(p => console.error('  ' + p))
  console.error('Fix it at the generator (mmg-tools/scripts/sync-pricing.js), not by hand-editing the generated file.')
  process.exit(1)
}
console.log(`Public data leak check passed: ${files.length} public data file(s) hold no TO, contract, markup or internal-note wording.`)
