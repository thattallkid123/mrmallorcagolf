/**
 * check-internal-links.mjs
 *
 * Guardrail for broken internal links. Scans content data (src/lib), components
 * (src/components) and pages (src/app) for internal href / route path string
 * literals and fails if any of them point at a route that does not exist.
 *
 * A path is considered valid if it resolves to:
 *   - a static route in the app router (src/app walk — route groups stripped),
 *   - a dynamic app route (e.g. /de/guides/[slug]) whose concrete path is
 *     confirmed published by hasLocaleRoute() in src/lib/site.js,
 *   - a file-convention route (/sitemap.xml, /robots.txt, /feed.xml),
 *   - a real file under public/ (asset links like /images/… or /downloads/…).
 *
 * Deliberately conservative to avoid false positives:
 *   - only extracts string literals in link positions (href attributes/keys,
 *     url/link/route/to keys, fetch() calls, buildPageMetadata() path args)
 *   - skips dynamic values (template literals with ${…}, variables)
 *   - strips ?query and #fragment before resolving
 *
 * Run: npm run check:links   (wired into check:content)
 */

import { readFileSync, readdirSync, existsSync, statSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join, resolve } from 'node:path'
import { hasLocaleRoute, getLocaleFromPath } from '../src/lib/site.js'

const __dirname = dirname(fileURLToPath(import.meta.url))
const REPO_ROOT = resolve(__dirname, '..')
const APP_DIR = join(REPO_ROOT, 'src', 'app')
const PUBLIC_DIR = join(REPO_ROOT, 'public')

// Directories whose .js/.jsx files are scanned for internal links.
const SCAN_DIRS = ['src/lib', 'src/components', 'src/app']

// Files with intentionally non-live route data (placeholder prototype data).
const SKIP_FILES = new Set(['src/lib/mallorca-tracker-courses.js'])

// File-convention routes generated by the app router, not directories.
const FILE_CONVENTION_ROUTES = new Set()
if (existsSync(join(APP_DIR, 'sitemap.js'))) FILE_CONVENTION_ROUTES.add('/sitemap.xml')
if (existsSync(join(APP_DIR, 'robots.js'))) FILE_CONVENTION_ROUTES.add('/robots.txt')

// Explicit allowlist of paths known to be legitimately absent (add sparingly).
const ALLOW = new Set([])

// ---------------------------------------------------------------------------
// Build the route registry from the app router filesystem
// ---------------------------------------------------------------------------

const staticRoutes = new Set(FILE_CONVENTION_ROUTES)
const dynamicRoutePatterns = [] // { pattern: RegExp, route: string }

function isRouteFile(name) {
  return /^(page|route)\.(jsx?|tsx?)$/.test(name)
}

function walkAppDir(dir, segments) {
  const entries = readdirSync(dir)
  if (entries.some(isRouteFile)) {
    const routePath = '/' + segments.join('/')
    if (segments.some((s) => s.startsWith('['))) {
      const pattern = new RegExp(
        '^/' +
          segments
            .map((s) => (s.startsWith('[') ? '[^/]+' : s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')))
            .join('/') +
          '$',
      )
      dynamicRoutePatterns.push({ pattern, route: routePath })
    } else {
      staticRoutes.add(segments.length ? routePath : '/')
    }
  }
  for (const entry of entries) {
    const entryPath = join(dir, entry)
    if (!statSync(entryPath).isDirectory()) continue
    if (entry.startsWith('_')) continue
    // Route groups like (en) add no URL segment
    const nextSegments =
      entry.startsWith('(') && entry.endsWith(')') ? segments : [...segments, entry]
    walkAppDir(entryPath, nextSegments)
  }
}

walkAppDir(APP_DIR, [])

// ---------------------------------------------------------------------------
// Extract internal link candidates from source files
// ---------------------------------------------------------------------------

// Link-position patterns. Each must capture the path (starting with /) in group 1.
const LINK_PATTERNS = [
  // href="/x", href='/x', href={'/x'}, href: '/x', href=\"/x\" (HTML inside strings)
  /href\s*[:=]\s*\{?\s*\\?["'](\/[^"'\\\s]*)\\?["']/g,
  // object keys commonly holding route paths in content data
  /\b(?:url|link|route|to)\s*:\s*["'](\/[^"'\s]*)["']/g,
  // API calls
  /\bfetch\(\s*["'](\/[^"'\s]*)["']/g,
  // canonical path arguments
  /\bbuildPageMetadata\(\s*["'](\/[^"'\s]*)["']/g,
]

function listSourceFiles() {
  const files = []
  function walk(dir) {
    for (const entry of readdirSync(dir)) {
      const entryPath = join(dir, entry)
      if (statSync(entryPath).isDirectory()) {
        walk(entryPath)
      } else if (/\.(jsx?|mjs)$/.test(entry)) {
        files.push(entryPath)
      }
    }
  }
  for (const rel of SCAN_DIRS) {
    const abs = join(REPO_ROOT, rel)
    if (existsSync(abs)) walk(abs)
  }
  return files.filter((abs) => !SKIP_FILES.has(toRel(abs)))
}

function toRel(absPath) {
  return absPath.slice(REPO_ROOT.length + 1).replace(/\\/g, '/')
}

function normalizeCandidate(raw) {
  const [pathOnly] = raw.split(/[?#]/)
  if (!pathOnly || pathOnly === '/') return '/'
  return pathOnly.endsWith('/') ? pathOnly.slice(0, -1) : pathOnly
}

function isFileLike(path) {
  const lastSegment = path.slice(path.lastIndexOf('/') + 1)
  return lastSegment.includes('.')
}

function publicFileExists(path) {
  return existsSync(join(PUBLIC_DIR, ...path.split('/').filter(Boolean)))
}

function resolveCandidate(path) {
  if (path === '/') return true
  if (staticRoutes.has(path)) return true
  if (isFileLike(path)) return publicFileExists(path)
  for (const { pattern } of dynamicRoutePatterns) {
    if (pattern.test(path)) {
      // Dynamic segment (locale guide slugs) — site.js decides what is published
      return hasLocaleRoute(path, getLocaleFromPath(path))
    }
  }
  return false
}

// ---------------------------------------------------------------------------
// Scan
// ---------------------------------------------------------------------------

let checkedCount = 0

function checkFile(absPath) {
  const rel = toRel(absPath)
  const lines = readFileSync(absPath, 'utf8').split('\n')
  const misses = []

  lines.forEach((line, idx) => {
    for (const pattern of LINK_PATTERNS) {
      pattern.lastIndex = 0
      let match
      while ((match = pattern.exec(line)) !== null) {
        const raw = match[1]
        if (raw.includes('${')) continue // dynamic — cannot resolve statically
        const path = normalizeCandidate(raw)
        if (ALLOW.has(path)) continue
        checkedCount += 1
        if (!resolveCandidate(path)) {
          misses.push({ line: idx + 1, raw, path })
        }
      }
    }
  })

  return { rel, misses }
}

function main() {
  const files = listSourceFiles()
  const results = files.map(checkFile).filter((r) => r.misses.length > 0)
  const total = results.reduce((n, r) => n + r.misses.length, 0)

  if (total === 0) {
    console.log(
      `✅ Internal link check passed — ${checkedCount} links in ${files.length} files, all resolve ` +
        `(${staticRoutes.size} static + ${dynamicRoutePatterns.length} dynamic routes).`,
    )
    return
  }

  console.error(`❌ Internal link check FAILED — ${total} link(s) to non-existent routes:\n`)
  for (const { rel, misses } of results) {
    console.error(`  ${rel}`)
    for (const { line, raw, path } of misses) {
      const note = raw === path ? '' : `  (from ${raw})`
      console.error(`    line ${line}: ${path}${note}`)
    }
    console.error('')
  }
  console.error(
    'Fix the link, register the route (src/lib/site.js or src/app), or — only for a\n' +
      'deliberate exception — add the path to the ALLOW set in scripts/check-internal-links.mjs\n' +
      'with a comment.',
  )
  process.exitCode = 1
}

main()
