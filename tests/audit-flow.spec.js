const { test, expect } = require('@playwright/test')
const ref='83b55c94-476f-47a3-8ff6-0b338299a4ec'
test('tool choices prefill the correct enquiry without submitting it',async({page})=>{
  let requests=0
  await page.route('**/api/contact',route=>{requests++;return route.abort()})
  const plan=encodeURIComponent(JSON.stringify({courses:'Golf Son Gual',message:'Golf and lunch in Palma'}))
  await page.goto('/contact?service=trip-planning#plan='+plan,{waitUntil:'networkidle'})
  await expect(page.locator('[name="courses"]')).toHaveValue('Golf Son Gual')
  await expect(page.locator('[name="message"]')).toHaveValue('Golf and lunch in Palma')
  expect(requests).toBe(0)
})
test('client draft survives a reload and clears after a successful mocked submission',async({page})=>{
  await page.route('**/api/trip-preferences',async route=>{
    const data=route.request().postDataJSON()
    await route.fulfill({json:data.action==='load-enquiry'?{ok:true,enquiry:{name:'Alex Example',email:'alex@example.com'}}:{ok:true}})
  })
  await page.goto('/trip-preferences.html?ref='+ref+'#context=test-context')
  await page.locator('[data-field="success"]').fill('Birthday golf with friends')
  await page.reload()
  await expect(page.locator('[data-field="success"]')).toHaveValue('Birthday golf with friends')
  await expect(page.getByText('Your original enquiry',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:/Review/}).first().click()
  await page.getByRole('button',{name:'Send preferences to Andy',exact:true}).click()
  await expect(page.getByRole('button',{name:'Sent to Andy',exact:true})).toBeVisible()
  expect(await page.evaluate(()=>Object.keys(sessionStorage).filter(k=>k.startsWith('mmg-trip-draft:')))).toEqual([])
})
test('quote request dialog supports labels, Escape and focus restoration',async({page})=>{
  await page.goto('/tools/golf-cost-calculator',{waitUntil:'networkidle'})
  await page.getByRole('button',{name:'Continue',exact:true}).click()
  await page.getByRole('button',{name:'Continue',exact:true}).click()
  await page.getByRole('button',{name:'See my estimate',exact:true}).click()
  const open=page.locator('.gcc-quote-cta button')
  await open.click()
  const dialog=page.getByRole('dialog')
  await expect(dialog).toBeVisible()
  await expect(dialog.locator('#quote-email')).toHaveAccessibleName(/email/i)
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
  await expect(open).toBeFocused()
})
