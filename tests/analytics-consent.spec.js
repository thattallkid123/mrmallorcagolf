const { test, expect } = require('@playwright/test')

test.use({ storageState: { cookies: [], origins: [] } })

test('first visit, rejection, persistence and reopening remain usable', async ({ page }, testInfo) => {
  const google = []
  page.on('request', (request) => { if (/google-analytics|googletagmanager/.test(request.url())) google.push(request.url()) })
  await page.goto('/subscribe', { waitUntil: 'domcontentloaded' })
  const panel = page.locator('.analytics-consent')
  await expect(panel).toBeVisible()
  await expect(panel.getByRole('button', { name: 'Accept analytics', exact: true })).toBeVisible()
  await expect(panel.getByRole('button', { name: 'Reject analytics', exact: true })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('consent-choice.png') })
  expect(google).toEqual([])
  expect((await page.context().cookies()).filter(c => c.name.startsWith('_ga'))).toEqual([])
  await panel.getByRole('button', { name: 'Reject analytics', exact: true }).click()
  await expect(panel).toBeHidden()
  await expect(page.getByRole('textbox', { name: /email/i }).first()).toBeEditable()
  await page.reload()
  await expect(panel).toBeHidden()
  expect(google).toEqual([])
  await page.getByRole('button', { name: 'Cookie settings', exact: true }).click()
  await expect(panel).toBeFocused()
  await panel.getByRole('button', { name: 'Accept analytics', exact: true }).click()
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('mmg-analytics-consent-v1')).choice)).toBe('accepted')
  await page.getByRole('button', { name: 'Cookie settings', exact: true }).click()
  await page.keyboard.press('Escape')
  await expect(panel).toBeHidden()
  await expect(page.getByRole('button', { name: 'Cookie settings', exact: true })).toBeFocused()
})

test('expired permission asks again and narrow screens fit', async ({ page }, testInfo) => {
  await page.addInitScript(() => localStorage.setItem('mmg-analytics-consent-v1', JSON.stringify({ choice: 'accepted', at: 1 })))
  await page.setViewportSize({ width: 320, height: 700 })
  await page.goto('/', { waitUntil: 'domcontentloaded' })
  await expect(page.locator('.analytics-consent')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  for (const button of await page.locator('.analytics-consent .btn').all()) {
    const box = await button.boundingBox()
    expect(box.height).toBeGreaterThanOrEqual(44)
    expect(box.x + box.width).toBeLessThanOrEqual(320)
  }
})

test('global missing address preserves 404 and useful recovery destinations', async ({ page }, testInfo) => {
  const response = await page.goto('/not-a-real-mmg-page')
  expect(response.status()).toBe(404)
  await expect(page.getByRole('heading', { name: 'Page not found', exact: true })).toBeVisible()
  expect(await page.locator('meta[name="robots"]').evaluateAll(tags => tags.length > 0 && tags.every(tag => tag.content.includes('noindex')))).toBe(true)
  for (const href of ['/', '/golf-courses', '/tools', '/contact']) await expect(page.locator(`a[href="${href}"]`).first()).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('missing-page.png') })
  await expect(page.locator('h1')).toHaveCSS('font-family', /cormorant/i)
  expect(await page.locator('img').evaluateAll(imgs => imgs.every(i => i.complete && i.naturalWidth > 0))).toBe(true)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
