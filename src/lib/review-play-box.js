export const REVIEW_PLAY_SECONDARY_EN = "Still narrowing down the trip? Start with Plan Your Trip and send me your dates, hotel area, handicap, and shortlist."

export function getReviewPlayBox(slug, locale) {
  const entry = REVIEW_PLAY_BOX_BY_SLUG[slug]
  if (!entry) return null
  const loc = REVIEW_PLAY_TEMPLATE[locale] ? locale : 'en'
  return {
    heading: REVIEW_PLAY_TEMPLATE[loc].replace('{course}', entry.course),
    button: REVIEW_PLAY_BUTTON[loc],
    quote: REVIEW_PLAY_QUOTES[entry.quote][loc],
    credit: entry.credit,
    photo: entry.photo,
    secondary: loc === 'en' ? REVIEW_PLAY_SECONDARY_EN : null,
  }
}
